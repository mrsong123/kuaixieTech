#!/usr/bin/env python3
"""Audit current Java mappings and literal SDK requests; does not prove runtime readiness.
Run from any directory. --write refreshes the full-route manifest and review report.
The core workbench registry remains separate and deliberately curated.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
VERBS = {'Get': 'GET', 'Post': 'POST', 'Put': 'PUT', 'Patch': 'PATCH', 'Delete': 'DELETE'}


def routes(source):
    source = re.sub(r'/\*.*?\*/|^\s*//[^\n]*', '', source, flags=re.S | re.M)
    base = ''
    class_at = re.search(r'\bclass\s+\w+', source)
    if class_at:
        prefix = source[:class_at.start()]
        mapping = re.search(r'@RequestMapping\s*\(([^)]*)\)', prefix)
        if mapping:
            values = re.findall(r'"([^"\n]*)"', mapping.group(1))
            if len(values) != 1:
                raise ValueError('Unsupported class mapping: ' + mapping.group(0))
            base = values[0]
    result = []
    for mapping in re.finditer(r'@(Get|Post|Put|Patch|Delete)Mapping\b(?:\s*\(([^)]*)\))?', source):
        args = mapping.group(2) or ''
        # First positional path or explicitly named path/value; never treat consumes/produces as paths.
        path = re.match(r'\s*(?:(?:value|path)\s*=\s*)?"([^"\n]*)"', args)
        if args.strip() and not path:
            raise ValueError('Unsupported method mapping: ' + mapping.group(0))
        result.append((VERBS[mapping.group(1)], (base + (path.group(1) if path else '')).removeprefix('/api') or '/'))
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    found = []
    for file in sorted((ROOT / 'server/src/main/java').rglob('*Controller.java')):
        text = file.read_text()
        if '@RestController' not in text:
            continue
        for method, path in routes(text):
            found.append({'method': method, 'path': path, 'controller': str(file.relative_to(ROOT))})
    keys = [(r['method'], r['path']) for r in found]
    if len(keys) != len(set(keys)):
        raise ValueError('Duplicate Java method + path mapping')
    sdk = (ROOT / 'client/packages/sdk/src/client.ts').read_text()
    requests = sorted(set(re.findall(r"\('(GET|POST|PUT|PATCH|DELETE)'\s*,\s*'([^']+)'(?=\s*[,\)])", sdk)))
    missing = [(method, path) for method, path in requests if (method, path) not in set(keys)]
    document = ['# 接口核验清单', '', '由 `python3 server/tools/audit_routes.py --write` 生成。', '',
                '此清单只核对 Java 声明和 SDK 字面量路径；不证明权限、数据库、外部服务或页面业务已验收。核心 API 工作台目录与全量清单分开维护。', '',
                f'当前 Java 接口 {len(found)} 项；SDK 字面量请求 {len(requests)} 项；其中 {len(missing)} 项未找到当前控制器。', '',
                '## SDK 中缺少后端声明的请求', '', '| 方法 | 路径 | 状态 |', '| --- | --- | --- |']
    document += [f'| {method} | `{path}` | 待实现或移除入口，不能当作可用能力 |' for method, path in missing]
    document += ['', '## 全量后端接口', '', '| 方法 | 路径 | 控制器 |', '| --- | --- | --- |']
    document += [f"| {r['method']} | `{r['path']}` | {Path(r['controller']).name} |" for r in found]
    manifest = '// GENERATED by server/tools/audit_routes.py --write; declaration coverage only.\nexport const declaredBackendRoutes = ' + json.dumps(found, ensure_ascii=False, indent=2) + ' as const;\n'
    outputs = {ROOT / 'client/packages/sdk/src/backendRoutes.ts': manifest,
               ROOT / 'client/docs/ROUTE_AUDIT.md': '\n'.join(document) + '\n'}
    if args.write:
        for file, content in outputs.items():
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
    else:
        for file, content in outputs.items():
            if not file.exists() or file.read_text() != content:
                raise SystemExit(f'Stale route audit: {file.relative_to(ROOT)}; regenerate with --write')
    print(f'{len(found)} Java routes; {len(requests)} literal SDK requests; {len(missing)} missing backend declarations (see client/docs/ROUTE_AUDIT.md)')


if __name__ == '__main__':
    main()
